package org.firstinspires.ftc.teamcode;

import com.pedropathing.follower.Follower;
import com.pedropathing.geometry.BezierLine;
import com.pedropathing.geometry.Pose;
import com.pedropathing.paths.PathChain;
import com.qualcomm.robotcore.eventloop.opmode.Autonomous;
import com.qualcomm.robotcore.eventloop.opmode.OpMode;
import com.qualcomm.robotcore.util.ElapsedTime;

import org.firstinspires.ftc.teamcode.pedroPathing.Constants; // generated by the Pedro quickstart
import org.firstinspires.ftc.teamcode.subsystems.Shooter;

/**
 * Auto: launch the 4 preloaded pollen into the hive's upward-facing cell to try to tip the hive
 * (20 pts), then park in the loading zone (LEAVE 3 + PARK 5).
 *
 * Field is 144 x 144 in, (0,0) bottom-left, heading in radians. The hive is at the center (72,72).
 * The pose numbers are PLACEHOLDERS for the BLUE-side corner next to the loading zone.
 * Measure the real start pose and loading zone on your field and edit the constants.
 */
@Autonomous(name = "BioBuzz Tip Hive + Park", group = "BioBuzz")
public class BioBuzzAutoTipHive extends OpMode {

    // ---- Field poses (EDIT THESE) ----
    private static final Pose START = new Pose(9, 40, Math.toRadians(0)); // touching wall, 4 pollen loaded
    private static final double HIVE_X = 72, HIVE_Y = 72;
    private static final double SHOOT_X = 40, SHOOT_Y = 56;               // ~35 in from the hive
    private static final Pose PARK = new Pose(14, 20, Math.toRadians(0)); // partly inside loading zone

    // ---- Shooting ----
    private static final int    SHOTS         = 4;
    private static final double SPINUP_MAX_S  = 3.0;  // give up waiting for speed after this
    private static final double FEED_PULSE_S  = 0.35; // feeder on time per element
    private static final double FEED_GAP_S    = 0.45; // wait for wheels to recover
    private static final double PARK_BY_S     = 26.0; // always leave time to park (auto is 30 s)

    private Follower follower;
    private Shooter shooter;
    private PathChain toShoot, toPark;
    private final ElapsedTime stateTimer = new ElapsedTime();
    private final ElapsedTime autoTimer = new ElapsedTime();
    private int state = 0;
    private int shotsFired = 0;
    private boolean feeding = false;

    @Override
    public void init() {
        follower = Constants.createFollower(hardwareMap);
        shooter = new Shooter(hardwareMap);
        follower.setStartingPose(START);

        // Face the hive when shooting
        double aim = Math.atan2(HIVE_Y - SHOOT_Y, HIVE_X - SHOOT_X);
        Pose shootPose = new Pose(SHOOT_X, SHOOT_Y, aim);

        toShoot = follower.pathBuilder()
                .addPath(new BezierLine(START, shootPose))
                .setLinearHeadingInterpolation(START.getHeading(), aim)
                .build();
        toPark = follower.pathBuilder()
                .addPath(new BezierLine(shootPose, PARK))
                .setLinearHeadingInterpolation(aim, PARK.getHeading())
                .build();
    }

    @Override
    public void start() {
        autoTimer.reset();
        shooter.setPollen();            // spin up while driving
        follower.followPath(toShoot, true);
        setState(0);
    }

    @Override
    public void loop() {
        follower.update();
        stepState();
        telemetry.addData("state", state);
        telemetry.addData("shots", shotsFired);
        telemetry.addData("flywheel", shooter.velocity());
        telemetry.addData("x", follower.getPose().getX());
        telemetry.addData("y", follower.getPose().getY());
        telemetry.addData("heading deg", Math.toDegrees(follower.getPose().getHeading()));
        telemetry.update();
    }

    private void stepState() {
        // Safety: if time is running out, abandon shooting and park.
        if (state < 3 && autoTimer.seconds() > PARK_BY_S) {
            shooter.stop();
            follower.followPath(toPark, true);
            setState(3);
            return;
        }
        switch (state) {
            case 0: // driving to the shoot pose
                if (!follower.isBusy()) setState(1);
                break;
            case 1: // wait for flywheel speed
                if (shooter.atSpeed() || stateTimer.seconds() > SPINUP_MAX_S) setState(2);
                break;
            case 2: // fire SHOTS elements, one pulse at a time
                if (shotsFired >= SHOTS) {
                    shooter.stop();
                    follower.followPath(toPark, true);
                    setState(3);
                } else if (!feeding && stateTimer.seconds() > FEED_GAP_S && (shooter.atSpeed() || stateTimer.seconds() > FEED_GAP_S + 1.0)) {
                    shooter.feed(Shooter.FEED_POWER);
                    feeding = true;
                    stateTimer.reset();
                } else if (feeding && stateTimer.seconds() > FEED_PULSE_S) {
                    shooter.feed(0);
                    feeding = false;
                    shotsFired++;
                    stateTimer.reset();
                }
                break;
            case 3: // driving to park
                if (!follower.isBusy()) setState(4);
                break;
            default: // done
                break;
        }
    }

    private void setState(int s) { state = s; stateTimer.reset(); }

    @Override
    public void stop() { shooter.stop(); }
}
